static inline uint16_t rgb888_to_rgb565(uint8_t r, uint8_t g, uint8_t b) {
    uint16_t color = (uint16_t)(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3));
    return (uint16_t)((color << 8) | (color >> 8));
}

void lcd_clear(uint16_t color) {
    uint16_t *buffer = (uint16_t *)malloc(LCD_WIDTH * sizeof(uint16_t));
    if (!buffer) return;
    for (int i = 0; i < LCD_WIDTH; i++) buffer[i] = color;
    for (int y = 0; y < LCD_HEIGHT; y++) {
        esp_lcd_panel_draw_bitmap(panel_handle, 0, y, LCD_WIDTH, y + 1, buffer);
    }
    free(buffer);
}

void lcd_draw_char(int x, int y, char c, uint16_t color) {
    if (c < 32 || c > 122) return;
    uint8_t c_idx = c - 32;
    uint16_t char_buf[8 * 8];
    
    for (int row = 0; row < 8; row++) {
        uint8_t bits = font8x8[c_idx][row];
        for (int col = 0; col < 8; col++) {
            if (bits & (1 << (7 - col))) {
                char_buf[row * 8 + col] = color;
            } else {
                char_buf[row * 8 + col] = 0x0000;
            }
        }
    }
    esp_lcd_panel_draw_bitmap(panel_handle, x, y, x + 8, y + 8, char_buf);
}

void lcd_draw_string(int x, int y, const char *str, uint16_t color) {
    while (*str) {
        lcd_draw_char(x, y, *str++, color);
        x += 8;
        if (x + 8 > LCD_WIDTH) break;
    }
}

void esp_ieee802154_receive_done(uint8_t *frame, esp_ieee802154_frame_info_t *frame_info) {
    zigbee_packet_count++;
    last_rssi = frame_info->rssi;
}

void app_main(void)
{
    esp_err_t ret = nvs_flash_init();
    if (ret == ESP_ERR_NVS_NO_FREE_PAGES || ret == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        ret = nvs_flash_init();
    }
    ESP_ERROR_CHECK(ret);

    spi_bus_config_t buscfg = {
        .sclk_io_num = TFT_SCLK,
        .mosi_io_num = TFT_MOSI,
        .miso_io_num = -1,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .max_transfer_sz = LCD_WIDTH * LCD_HEIGHT * sizeof(uint16_t),
    };
    ESP_ERROR_CHECK(spi_bus_initialize(SPI2_HOST, &buscfg, SPI_DMA_CH_AUTO));

    esp_lcd_panel_io_handle_t io_handle = NULL;
    esp_lcd_panel_io_spi_config_t io_config = {
        .dc_gpio_num = TFT_DC,
        .cs_gpio_num = TFT_CS,
        .pclk_hz = 10 * 1000 * 1000, 
        .lcd_cmd_bits = 8,
        .lcd_param_bits = 8,
        .spi_mode = 0,
        .trans_queue_depth = 10,
    };
    ESP_ERROR_CHECK(esp_lcd_new_panel_io_spi((esp_lcd_spi_bus_handle_t)SPI2_HOST, &io_config, &io_handle));

    esp_lcd_panel_dev_config_t panel_config = {
        .reset_gpio_num = TFT_RST,
        .bits_per_pixel = 16,
    };
    ESP_ERROR_CHECK(esp_lcd_new_panel_st7735(io_handle, &panel_config, &panel_handle));
    ESP_ERROR_CHECK(esp_lcd_panel_reset(panel_handle));
    ESP_ERROR_CHECK(esp_lcd_panel_init(panel_handle));
    
    // Aliniere culori si orientare MADCTL pentru Green Tab
    ESP_ERROR_CHECK(esp_lcd_panel_invert_color(panel_handle, false)); 
    esp_lcd_panel_io_tx_param(io_handle, 0x36, (uint8_t[]){0xC8}, 1); 

    // --- REPARARE FRAGMENTARE TEXT (Setare manuala Offset-uri ferastra hardware) ---
    // Setează decalajul intern de memorie specific ecranelor ST7735 clona
    esp_lcd_panel_set_gap(panel_handle, 2, 1); 

    ESP_ERROR_CHECK(esp_lcd_panel_disp_on_off(panel_handle, true));

    uint16_t color_white  = rgb888_to_rgb565(255, 255, 255);
    uint16_t color_green  = rgb888_to_rgb565(0, 255, 0);
    uint16_t color_yellow = rgb888_to_rgb565(255, 255, 0);

    lcd_clear(0x0000);

    lcd_draw_string(5, 5,   "ZIGBEE TESTER",       color_yellow);
    lcd_draw_string(5, 20,  "Platforma: XIAO C6",  color_white);
    lcd_draw_string(5, 35,  "Driver: ST7735 GT",   color_white);
    lcd_draw_string(5, 50,  "Mode: SNIFFER",       color_white);

    ESP_LOGI(TAG, "Sistem Radio pornit.");

    esp_ieee802154_enable();
    esp_ieee802154_set_promiscuous(true);
    esp_ieee802154_set_channel(current_channel);
    esp_ieee802154_receive();

    char buff[32]; // FIX DEFINITIV: Vector stabil, ocoleste crash-ul de tip stack overflow

    while (1) {
        snprintf(buff, sizeof(buff), "Canal: %d    ", current_channel);
        lcd_draw_string(5, 75, buff, color_white);

        snprintf(buff, sizeof(buff), "Pachete: %lu   ", zigbee_packet_count);
        lcd_draw_string(5, 95, buff, color_green);

        snprintf(buff, sizeof(buff), "RSSI: %d dBm   ", last_rssi);
        lcd_draw_string(5, 115, buff, color_green);

        current_channel++;
        if (current_channel > 26) {
            current_channel = 11;
        }
        esp_ieee802154_set_channel(current_channel);
        esp_ieee802154_receive();

        vTaskDelay(pdMS_TO_TICKS(500));
    }
}




